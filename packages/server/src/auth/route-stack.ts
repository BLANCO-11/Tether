import type { Express } from "express";
import { guardMarker } from "../middleware/require-permission.middleware.js";
import { platformGuardMarker } from "../middleware/platform-permission.middleware.js";
import { appStack, mountPathOf } from "./express-mount.js";

/**
 * Walk a mounted Express application and report every reachable route.
 *
 * ⚠ **THIS READS EXPRESS INTERNALS** — the router stack, and each mount's path as
 * `recordMountPaths` stamped it (`express-mount.ts`; Express 5 keeps no path on the layer). That is a real cost and it is taken deliberately, for the
 * same reason `wrapAsyncRoutes` in `middleware/async-routes.ts` already takes it on this
 * codebase: the alternative is a regex over route source, which reports **nine false
 * positives on `local-users.ts` alone** because that file is guarded at the router
 * rather than per handler (research M-5). A check with nine false positives gets widened
 * until the widening permits the defect (I-62).
 *
 * The map in `route-permissions.ts` was GENERATED by a walker of exactly this shape, and
 * `route-permissions.test.ts` re-walks with this one — so the generator and the checker
 * cannot disagree about what "the routes" means.
 *
 * ⚠ **Dedupes on `(method, resolved path)`.** `GET /flows/:flowId/phases` is registered
 * twice (`flows.ts` has the implementation; `flow-phases.ts`'s router is an unreachable
 * placeholder) and `releaseGatesRouter` is mounted twice. Without the dedupe the walk
 * reports duplicates that are not map errors.
 */

interface Layer {
  name?: string;
  slash?: boolean;
  route?: { path?: string; stack?: { method?: string; name?: string; handle?: unknown }[] };
  handle?: { stack?: Layer[] } & Function;
}

export interface MountedRoute {
  method: string;
  path: string;
  /**
   * Named middleware on the handler chain, in order, deduplicated.
   *
   * ⚠ **A NAMELESS CHAIN IS NOT AN UNGUARDED ROUTE.** `asyncHandler` returns an
   * anonymous arrow, so every guard built through it — `requireWorkspaceRole` included —
   * arrives here with no name at all. Do not write "does this route carry a role guard"
   * as a test over these strings: it finds nothing and passes over an empty set. Use
   * `rbac` below, which is a deliberate marker rather than an incidental name.
   */
  guards: string[];
  /**
   * The permission declared by a mounted `requirePermission`, when one is present.
   * This is what the mount assertion checks against the map — presence alone would be
   * satisfied by every route carrying the same wrong guard.
   */
  rbac?: { permission: string; param: string };
  /** The content the content guard checks on this route (rbac-observability), when it has one. */
  content?: string[];
}


export function mountedRoutes(app: Express): MountedRoute[] {
  const rows = new Map<string, MountedRoute>();

  function walk(stack: Layer[] | undefined, prefix: string) {
    for (const layer of stack ?? []) {
      if (layer.route) {
        const rp = layer.route.path === "/" ? "" : (layer.route.path ?? "");
        const path = prefix + rp || "/";
        const guards = [
          ...new Set(
            (layer.route.stack ?? [])
              .map((h) => h.name)
              .filter(
                (n): n is string =>
                  !!n && n !== "<anonymous>" && n !== "handle" && !n.startsWith("bound "),
              ),
          ),
        ];
        const methods = [
          ...new Set((layer.route.stack ?? []).map((h) => h.method).filter(Boolean)),
        ];
        let rbac: { permission: string; param: string } | undefined;
        let contentKinds: string[] | undefined;
        for (const h of layer.route.stack ?? []) {
          const marker = guardMarker(h.handle);
          if (marker) rbac = { permission: marker.permission, param: marker.param };
          // A platform guard answers about a PERSON, so it has no workspace parameter.
          // `param: ""` says so rather than implying one.
          const plat = platformGuardMarker(h.handle);
          if (plat) rbac = { permission: plat.permission, param: "" };
          const content = (h.handle as Record<symbol, string[] | undefined> | undefined)?.[Symbol.for("foundry.rbac.contentGuard")];
          if (content) contentKinds = content;
        }
        for (const m of methods) {
          const method = m!.toUpperCase();
          // ⚠ Dedupe, but UNION the guards: a route registered twice must not lose the
          // guard the second registration carries just because the first was seen first.
          const key = `${method} ${path}`;
          const seen = rows.get(key);
          rows.set(key, {
            method,
            path,
            guards: seen ? [...new Set([...seen.guards, ...guards])] : guards,
            rbac: rbac ?? seen?.rbac,
            ...(contentKinds ?? seen?.content ? { content: contentKinds ?? seen?.content } : {}),
          });
        }
      } else if (layer.handle && (layer.handle as { stack?: Layer[] }).stack) {
        walk((layer.handle as { stack?: Layer[] }).stack, prefix + mountPathOf(layer));
      }
    }
  }

  walk(appStack<Layer>(app), "");
  return [...rows.values()].sort((a, b) =>
    `${a.method} ${a.path}`.localeCompare(`${b.method} ${b.path}`),
  );
}
