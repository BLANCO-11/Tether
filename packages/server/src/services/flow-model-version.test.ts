describe("flow-model-version — the upgrade is not a rewrite", () => {
  it("the fixture is genuinely v1", () => {
    expect(v1()).not.toHaveProperty("version");
  });

  it("normalise upgrades calls, code, branch and approvals to typed fields", () => {
    const v2 = normaliseModel(v1()) as unknown as FlowModel;
    expect(v2.version).toBe(2);
    const byId = new Map(v2.steps.map((s) => [s.id, s]));
    const screen = byId.get("screen");
    expect(screen).toMatchObject({ kind: "datasource" });
    if (screen?.kind !== "datasource" && screen?.kind !== "tool" && screen?.kind !== "query") {
      throw new Error("fixture drifted");
    }
    // Single with an input mapping: converted, display dropped.
    expect(screen.inputs).toHaveLength(1);
    expect(screen).not.toHaveProperty("paramsExpr");
    // Fan-out with a where-predicate: converted, display dropped.
    const severe = byId.get("severe");
    if (severe?.kind !== "tool" && severe?.kind !== "datasource" && severe?.kind !== "query") {
      throw new Error("fixture drifted");
    }
    expect(severe.over).toMatchObject({ stepId: "screen" });
    expect(severe.where).toMatchObject({ field: "attendance_rate", test: "field_lt" });
    expect(severe).not.toHaveProperty("paramsExpr");
    // Branch: typed test replaces the display string.
    const check = byId.get("check");
    if (check?.kind !== "branch") throw new Error("fixture drifted");
    expect(check.test).toMatchObject({ operator: "field_eq" });
    expect(check).not.toHaveProperty("conditionExpr");
    // Approval literal: summary text replaces the JSON string.
    const triage = byId.get("triage");
    if (triage?.kind !== "approval") throw new Error("fixture drifted");
    expect(triage.summary).toBe("Send the exceptions?");
    expect(triage).not.toHaveProperty("summaryExpr");
    // Approval computed: summary text plus a whole-rows context.
    const triage2 = byId.get("triage2");
    if (triage2?.kind !== "approval") throw new Error("fixture drifted");
    expect(triage2.summary).toBe("Send to ");
    expect(triage2.context).toMatchObject({ from: "whole", stepId: "screen" });
    expect(triage2).not.toHaveProperty("summaryExpr");
    // Hand-shaped: kept as written.
    const odd = byId.get("odd");
    if (odd?.kind !== "tool" && odd?.kind !== "datasource" && odd?.kind !== "query") {
      throw new Error("fixture drifted");
    }
    expect(odd.paramsExpr).toBe("{{ custom(1, 2) }}");
  });

  it("entry normalise is transparent: v1 and v2 compile to the same bytes", () => {
    const a = flowCompiler.compile(v1() as unknown as FlowModel, { namespace: draft }).yaml;
    const b = flowCompiler.compile(normaliseModel(v1()) as unknown as FlowModel, {
      namespace: draft,
    }).yaml;
    expect(a).toBe(b);
  });

  it("compiles to byte-identical YAML to the recorded output — but for the escaped input spelling (I-288)", async () => {
    const { toLegacyInputSpelling } = await import("@foundry/flow-edit");
    const yaml = flowCompiler.compile(v1() as unknown as FlowModel, { namespace: draft }).yaml;
    // ⚠ The ONE sanctioned difference: an input is now an escaped JSON literal (`(inputs.x ~ '') | toJson`), which the
    // recorded output wrote unescaped between quotes. Mapped back, every other byte must still be identical.
    expect(toLegacyInputSpelling(yaml)).toBe(GOLDEN);
    expect(yaml).not.toBe(GOLDEN); // CONTROL: the fixture does carry an input, so the mapping is exercised
  });
});

describe("a filter the typed form cannot hold keeps the step as written (phase 7, showcase `mild`)", () => {
  const model = (filter: string) => ({
    id: "f",
    steps: [
      { id: "screen", kind: "datasource", ref: "hr.rows", paramsExpr: "[{}]" },
      {
        id: "mild",
        kind: "tool",
        ref: "chat_post_message",
        paramsExpr: `{{ json(outputs.screen.body).results[0].data | jq('[.[] | select(${filter}) | {"channel": "#hr-ops", "text": .full_name}]') | first }}`,
        dependsOn: ["screen"],
      },
    ],
  });
  it("`>= 70` has no stored where: no bindings and no over are carried beside the text", async () => {
    const { normaliseModel } = await import("@foundry/flow-edit");
    const s = (normaliseModel(model("(.attendance_rate | tonumber?) >= 70") as never) as { steps: Array<Record<string, unknown>> }).steps[1]!;
    expect(s.paramsExpr).toContain(">= 70");
    expect(s.inputs).toEqual([]);
    expect(s.over).toBeUndefined();
  });
  it("CONTROL: a filter it CAN store still converts to over + where + bindings", async () => {
    const { normaliseModel } = await import("@foundry/flow-edit");
    const s = (normaliseModel(model('.status == "active"') as never) as { steps: Array<Record<string, unknown>> }).steps[1]!;
    expect(s.over).toMatchObject({ stepId: "screen" });
    expect((s.inputs as unknown[]).length).toBeGreaterThan(0);
  });
});

describe("a model the server stored can be posted back to it (phase 7, kestra:canvas)", () => {
  it("the upgrade drops paramsExpr on a converted step, and the route's schema accepts that", async () => {
    const { normaliseModel } = await import("@foundry/flow-edit");
    const { flowModelSchema } = await import("./flow.service.js");
    const stored = normaliseModel({
      id: "f",
      steps: [
        { id: "read", kind: "datasource", ref: "hr.rows", paramsExpr: "[{}]" },
        { id: "send", kind: "tool", ref: "chat_post_message", paramsExpr: `{{ json(outputs.read.body).results[0].data | jq('[.[] | {"channel": "#hr-ops", "text": .full_name}]') | first }}`, dependsOn: ["read"] },
      ],
    } as never) as { steps: Array<Record<string, unknown>> };
    expect("paramsExpr" in stored.steps[1]!).toBe(false); // the upgrade converted it
    const r = flowModelSchema.safeParse(stored);
    expect(r.success, JSON.stringify(!r.success && r.error.issues)).toBe(true);
  });
});
