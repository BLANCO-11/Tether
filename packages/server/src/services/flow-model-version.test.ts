/**
 * The version upgrade is not a rewrite — the byte-identical proof.
 *
 * A recorded version-1 model (no `version` key, display strings only — the
 * shape every revision in history carries) normalises to v2 and compiles to
 * BYTE-IDENTICAL YAML to the pre-change compiler output for the same fixture.
 * Every expression below is either builder-canonical (the upgrade parses it,
 * drops the display string, and `render.ts` rebuilds the same bytes) or
 * hand-shaped (the upgrade keeps it as written with null bindings and the
 * compiler emits it verbatim). Either path must leave the YAML untouched:
 * an upgrade that rewrites history's meaning is a migration that deploys
 * unapproved behaviour.
 *
 * The fixture covers every converted kind (call single + fan-out with a
 * where-predicate, code, branch, approval literal + computed) plus one
 * hand-shaped call the upgrade cannot read. Transform needs no case: `expr`
 * is never dropped, so its path is verbatim by construction.
 *
 * If this test fails on the GOLDEN after an emitter change, re-take the
 * golden deliberately (compile the fixture, read the YAML, confirm the
 * canonical strings are intact) — never by pasting blind output.
 */
