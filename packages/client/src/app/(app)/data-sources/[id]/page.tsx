// src/app/(app)/data-sources/[id]/page.tsx — one data source: live status, the
// schema Foundry introspected, and the two real actions (re-test, re-scan).
//
// ── THE "MOCK DATA" SECTION IS GONE ─────────────────────────────────────────
//
// It let you upload JSON or CSV rows per table, listed them with row counts, and
// let you delete them. All of it lived in `lib/mockdb.ts` — a browser
// localStorage blob. Nothing was ever uploaded anywhere, no automation could read
// it, and the warning above it ("stored in plaintext and shown to the AI during
// design-time testing") described a data path that did not exist. Uploading real
// rows there would have put them in the browser and nowhere else, which is a worse
// outcome than the warning implied.
//
// ── THE ROW PREVIEW IS NOW A COLUMN VIEW, AND THAT IS THE HONEST VERSION ────
//
// Clicking a table used to show 20 "sample rows". The server has no row-sampling
// endpoint, so those rows were generated by `lib/mock-rows.ts` from the column
// types — invented values wearing a real table's column names, labelled "synthetic
// sample" in a pill most people would not read as "none of this is your data".
//
// What the server genuinely knows is the SCHEMA, and it knows it precisely: type,
// nullability, primary keys, and foreign keys resolved through
// `pg_constraint.conkey/confkey` so a multi-column FK pairs its columns correctly.
// That is what the modal shows now. Introspection also runs as the read-only role,
// so this is exactly the surface an automation can see — which makes it useful
// rather than decorative.
