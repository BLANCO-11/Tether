// Shared with the list page and /keys — see `lib/connection-status.ts`. Three
// copies of this map is how a new state ends up worded three different ways.
const PILL = CONNECTION_PILL;

type TableRef = { schema: string; table: string; columns: string[] };

function tableList(nodes: AssetNode[]): TableRef[] {
  const out: TableRef[] = [];
  for (const schema of nodes) {
    if (schema.asset_type !== "db_schema") continue;
    for (const table of schema.children ?? []) {
      if (table.asset_type !== "table") continue;
      const columns = (table.children ?? [])
        .filter((c) => c.asset_type === "column")
        .map((c) => c.name);
      out.push({ schema: schema.name, table: table.name, columns });
    }
  }
  return out;
}

/** One introspected column, as the schema view renders it. */
type ColumnView = {
  name: string;
  type: string;
  nullable: boolean;
  primaryKey: boolean;
  foreignKey?: string;
  /** The column's tag — the schema's own, or the owner's declaration. */
  tag?: string;
};

/** Text columns are the ones that can hold an address (the server checks the same; this only decides what is offered). */
const TEXTUAL = /^(text|character varying|varchar|char|character|citext|name|bpchar)/i;

/** The table node with this name in the schema tree, if it is there. */
function findNode(nodes: AssetNode[], name: string): AssetNode | undefined {
  for (const s of nodes) for (const t of s.children ?? []) if (t.asset_type === "table" && t.name === name) return t;
  return undefined;
}

function columnsOf(node: AssetNode): ColumnView[] {
  return (node.children ?? [])
    .filter((c) => c.asset_type === "column")
    .map((c) => {
      const a = (c.attributes ?? {}) as Record<string, unknown>;
      return {
        name: c.name,
        type: String(a.type ?? "unknown"),
        nullable: a.nullable !== false,
        primaryKey: a.primary_key === true,
        foreignKey: typeof a.foreign_key === "string" ? a.foreign_key : undefined,
        tag: typeof a.tag === "string" ? a.tag : undefined,
      };
    });
}

export default function ConnectionDetailPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const toast = useToast();
  const { workspaceId } = useWorkspace();
  const { data: workspaces } = useAsync(listWorkspaces, [workspaceId]);

  const { data: conn, loading, error, reload: reloadConn } = useAsync(() => getConnection(id));
  const { data: metadata, reload: reloadMeta } = useAsync(() => getConnectionMetadata(id));

  usePoll(reloadConn, !!conn && conn.status === "discovering");
  const [inspect, setInspect] = useState<{ title: string; keyPrefix: string; node: AssetNode } | null>(null);
  const [tagging, setTagging] = useState<string | null>(null);
  const [confirmDel, setConfirmDel] = useState(false);
  const [busy, setBusy] = useState<"test" | "scan" | "credential" | "pause" | null>(null);
  // The credential NAME being attached — a reference, never a value. Seeded
  // from the row, written through `setDatasourceCredentialName`.
  const [credentialName, setCredentialName] = useState<string | null | undefined>(undefined);
  const tables = useMemo(() => tableList(metadata ?? []), [metadata]);

  // Engine words for the header's purpose line (the mock's "PostgreSQL 16 ·
  // workspace: HR · …"). Version is not in the payload, so the label has none.
  const ENGINE_LABELS: Record<string, string> = {
    postgres: "PostgreSQL",
    mysql: "MySQL",
  };

  /** Show what the server introspected for this table. No invented rows. */
  const doInspect = (node: AssetNode) => {
    const ref = tables.find((t) => t.table === node.name);
    const schema = (node.attributes as Record<string, unknown> | undefined)?.schema;
    setInspect({
      title: ref ? `${ref.schema}.${ref.table}` : node.name,
      // The declaration key the server reads: `[schema.]table.column`.
      keyPrefix: `${typeof schema === "string" && schema ? `${schema}.` : ""}${node.name}.`,
      node,
    });
  };

  /**
   * Declare (or withdraw) that a column holds an email address. The server re-reads the schema with the new set and refuses,
   * naming the column, anything it cannot honour — so the toast says why, and nothing half-applies.
   */
  const toggleEmail = async (key: string, on: boolean) => {
    const next = { ...(conn?.column_tags ?? {}) };
    if (on) next[key] = "email";
    else delete next[key];
    setTagging(key);
    try {
      await setConnectionColumnTags(id, next);
      await Promise.all([reloadConn(), reloadMeta()]);
      toast.success(on ? `${key} is declared an email address` : `${key} is no longer declared an email address`);
    } catch (e) {
      toast.error(`Not saved: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setTagging(null);
    }
  };

  const runTest = async () => {
    setBusy("test");
    try {
      await testConnection(id);
      toast.success("Connection works");
    } catch (e) {
      // The database's own complaint, not a paraphrase of it.
      toast.error(`Couldn't connect: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setBusy(null);
      reloadConn();
    }
  };

  const rescan = async () => {
    setBusy("scan");
    try {
      await refreshConnectionSchema(id);
      toast.success("Schema re-scanned");
    } catch (e) {
      toast.error(`Couldn't read the schema: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setBusy(null);
      reloadConn();
      reloadMeta();
    }
  };

  /**
   * Pause — hide this source from the model — or resume it.
   *
   * ⚠ **No confirmation, unlike Remove, and that asymmetry is the point.**
   * Nothing is destroyed, nothing running stops, and the same button undoes it.
   * A dialog in front of a reversible act is how people learn to click through
   * the one in front of the irreversible act sitting a few lines below this.
   */
  const togglePause = async () => {
    if (!conn) return;
    const next = !conn.paused_from_model;
    setBusy("pause");
    try {
      await setDatasourcePaused(id, next);
      toast.success(
        next
          ? `"${conn.name}" is paused — the designer will not be shown it.`
          : `"${conn.name}" is back in the designer's catalogue.`,
      );
    } catch (e) {
      toast.error(`Couldn't change it: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setBusy(null);
      reloadConn();
    }
  };

  const remove = async () => {
    try {
      await deleteConnection(id);
      toast.success(`Removed "${conn?.name}"`);
      router.push("/data-sources");
    } catch (e) {
      toast.error(`Couldn't remove it: ${e instanceof Error ? e.message : String(e)}`);
    }
  };

  // Attach or detach the credential NAME (a reference — values are write-only
  // and never travel here). Detach sends null; the server clears the reference
  // without touching the stored value.
  const saveCredential = async (name: string | null) => {
    setBusy("credential");
    try {
      await setDatasourceCredentialName(id, name);
      setCredentialName(name);
      toast.success(name ? `Credential "${name}" attached` : "Credential detached");
    } catch (e) {
      toast.error(`Couldn't save the credential: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setBusy(null);
      reloadConn();
    }
  };

  if (loading) {
    return (
      <Page>
        <Zone name="content"><p className="text-sm text-muted">Loading…</p></Zone>
      </Page>
    );
  }
  if (error) {
    return (
      <Page>
        <Zone name="notices">
          <Notice tone="danger" title="Could not load this data source">{error}</Notice>
        </Zone>
      </Page>
    );
  }
  if (!conn) {
    const deadWs = (workspaces ?? []).find((w) => w.id === workspaceId)?.name;
    return (
      <Page>
        <Zone name="content">
          <Notice
            tone="warn"
            title="This data source is not in this workspace"
            action={
              <Link href="/data-sources">
                <Button size="sm">Back to data sources</Button>
              </Link>
            }
          >
            {deadWs
              ? `You are looking at the ${deadWs} workspace, which holds no source with this id. It may live in another workspace — switch workspace to see it.`
              : "It may live in another workspace — switch workspace to see it."}
          </Notice>
        </Zone>
      </Page>
    );
  }

  const pill = PILL[conn.status];
  const wsName = (workspaces ?? []).find((w) => w.id === workspaceId)?.name;
  const engineLabel = ENGINE_LABELS[conn.connector_id] ?? conn.connector_id;
  // The frozen mock's purpose line (D-02): engine · workspace · schema-only
  // visibility. Clauses without data are omitted.
  const purposeLine = [engineLabel, wsName ? `workspace: ${wsName}` : null, "schema-only visibility for operations."]
    .filter((p): p is string => Boolean(p))
    .join(" · ");

  /**
   * What a column holds, as declared. A tag the SCHEMA gave (or one a view takes from its source column) is shown and not
   * editable here; a text column with none can be declared an email address, and one declared here can be withdrawn.
   */
  const holds = (c: ColumnView, prefix: string) => {
    const key = `${prefix}${c.name}`;
    const declared = conn?.column_tags?.[key];
    if (c.tag && !declared) return <span className="text-xs text-muted">{c.tag === "email" ? "email address" : c.tag}</span>;
    if (!TEXTUAL.test(c.type) && !declared) return null;
    return (
      <label className="inline-flex items-center gap-1.5 text-xs">
        <input
          type="checkbox"
          checked={declared === "email"}
          disabled={tagging !== null}
          onChange={(e) => void toggleEmail(key, e.target.checked)}
          aria-label={`${c.name} holds an email address`}
        />
        email address
      </label>
    );
  };

  const columnRows = (cols: ColumnView[], prefix: string): DataRow<"column">[] =>
    cols.map((c) => ({
      key: c.name,
      cells: {
        identity: <span className="font-mono text-xs">{c.name}</span>,
        kind: <span className="font-mono text-xs text-muted">{c.type}</span>,
        nullable: <span className="text-xs text-muted">{c.nullable ? "yes" : "no"}</span>,
        keyRole: (
          <span className="text-xs">
            {c.primaryKey && <Tag>primary key</Tag>}
            {c.foreignKey && (
              <span className="font-mono text-xs text-muted" title={c.foreignKey}>
                → {c.foreignKey}
              </span>
            )}
          </span>
        ),
        holds: holds(c, prefix),
      },
    }));

  return (
    <Page>
      {/* ⚠ TWO actions, not three. "Remove" was the third, sitting beside two
          safe ones — and `PageHeader`'s action tuple caps the slot at two by
          ARITY, so `tsc` refuses a third rather than a reviewer counting them
          (D-93). Removing a data source is destructive and irreversible for
          every flow that reads it, so it moved to zone 5 beside the sentence
          that says what it costs.
          The mock's "Edit" action has no page-level equivalent — the real
          actions here are Test connection and Re-scan schema, and both stay. */}
      <PageHeader
        eyebrow={["Data source", engineLabel, wsName].filter(Boolean).join(" · ")}
        title={conn.name}
        // The frozen mock's inline header badge cluster (D-02): the status pill
        // and the connector/credential tags moved up from zone 2.
        badge={
          <>
            <StatusPill status={pill.status}>{pill.text}</StatusPill>
            <Tag>{engineLabel}</Tag>
            <Tag>
              {conn.credential_source === "secret_ref"
                ? `credential name: ${conn.secret_env_name}`
                : "no credential name declared"}
            </Tag>
          </>
        }
        purpose={purposeLine}
        actions={[
          { label: busy === "test" ? "Testing…" : "Test connection", onClick: runTest, disabled: busy !== null },
          { label: busy === "scan" ? "Scanning…" : "Re-scan schema", onClick: rescan, disabled: busy !== null },
        ]}
      />

      <Zone name="notices" gap="tight">
        {conn.last_tested_at && (
          <p className="text-xs text-muted">
            last tested {new Date(conn.last_tested_at).toLocaleString()}
          </p>
        )}
        {conn.description && (
          <p className="text-xs text-muted">{conn.description}</p>
        )}

        {conn.status === "error" && (
          <Notice tone="danger" title="This data source could not be reached">
            {conn.error_message ?? "The last test could not connect. Press Test connection to see the database's answer."}
          </Notice>
        )}
      </Zone>

      <Zone name="content">
        {/* The frozen mock's 2-column detail grid (D-02): a Schema pane on the
            left, the Mock, Named queries and DB operations panes on the right.
            Inline style, as the mock itself declares it: the honest-check rule
            ("no page owns a row grid") is about TABLE rows, which must live in
            DataTable sets — this is a page LAYOUT, and the mock froze it as a
            fixed pane + flexible column. 320px, not 260px: at 260 the table
            names AND the per-row "View schema" affordance both truncated, so
            the one control that reaches a table's shape was unreadable. */}
        <div className="grid min-w-0 items-start gap-4" style={{ gridTemplateColumns: "320px minmax(0,1fr)" }}>
          <div id="schema" className="min-w-0 rounded-lg border border-line bg-surface">
            <div className="flex items-center gap-2 border-b border-line px-4 py-3">
              <h2 className="text-body font-semibold text-text">Schema</h2>
              {tables.length > 0 && (
                <span className="ml-auto rounded-full bg-surface-2 px-2.5 py-0.5 text-xs text-muted">
                  {tables.length} {tables.length === 1 ? "table" : "tables"}
                </span>
              )}
            </div>
            <div className="p-2">
              {tables.length > 0 ? (
                <AssetTree nodes={metadata ?? []} onPreview={doInspect} />
              ) : conn.status === "error" ? (
                <p className="p-3 text-sm text-muted">
                  Tether couldn&apos;t read this source&apos;s schema — fix the connection above, then
                  re-scan.
                </p>
              ) : (
                <p className="p-3 text-sm text-muted">
                  No tables discovered yet. Re-scan the schema to look again.
                </p>
              )}
            </div>
            <p className="border-t border-line px-4 py-2 text-caption text-muted">
              Read using the same read-only credential an automation gets — exactly the surface a
              flow can query, nothing more.
            </p>
          </div>

          <div className="flex min-w-0 flex-col gap-4">

            {/* Mock data in ONE card: the readiness status off the fixture row
                (the state a test run keys on) above the mock-rows viewer. Two
                stacked cards said near-identical things ("Mock data is ready…"
                + "Mock data — never production"); the single header carries the
                banner and both children render bare beneath it. */}
            <section aria-label="Mock data" className="min-w-0 rounded-lg border border-line bg-surface p-4">
              <h2 className="text-body font-semibold text-text">Mock data — never production</h2>
              <p className="mt-1 text-xs text-muted">
                Generated rows for design-time testing. They share the schema, never the records.
              </p>
              <MockPanel bare datasourceId={id} tableCount={tables.length} />
              {/* Mock rows, not production. The only row read on this page. */}
              <div id="mock-rows" className="mt-3">
                <MockViewer bare datasourceId={id} tables={tables.map((t) => t.table)} />
              </div>
            </section>

            {/* Access & guardrails: the credential NAME this source is referenced
                by. References only — values are write-only and never read back. */}
            <section aria-label="Access and guardrails" className="rounded-lg border border-line bg-surface p-4">
              <h2 className="text-body font-semibold text-text">Access &amp; guardrails</h2>
              <p className="mt-1 text-xs text-muted">
                Test runs read mock data unless an admin opts a run into production with a reason —
                every opt-in is audited. Writes and multi-statements are refused on both paths.
              </p>
              <div className="mt-3">
                <CredentialPicker
                  value={credentialName !== undefined ? credentialName : (conn.secret_env_name ?? null)}
                  onPick={setCredentialName}
                  disabled={busy !== null}
                />
              </div>
              {(credentialName !== undefined ? credentialName : (conn.secret_env_name ?? null)) !== (conn.secret_env_name ?? null) && (
                <div className="mt-3 flex flex-wrap gap-2">
                  <Button
                    size="sm"
                    onClick={() => saveCredential(credentialName ?? null)}
                    disabled={busy !== null}
                  >
                    {busy === "credential" ? "Saving…" : "Save credential"}
                  </Button>
                  <Button
                    size="sm"
                    variant="ghost"
                    onClick={() => setCredentialName(conn.secret_env_name ?? null)}
                    disabled={busy !== null}
                  >
                    Cancel
                  </Button>
                </div>
              )}
            </section>

            {/* The callable catalogue. A `query` step names an operation from
                here; it never carries SQL, which is why this panel is what
                makes such a step authorable at all. Only schema metadata is
                ever shown — the builder previews the COMPILED SQL, never data
                rows. */}
            <DbOperationsPanel datasourceId={id} schema={metadata ?? []} />
          </div>
        </div>
      </Zone>

      <Zone name="related">
        <p className="text-sm text-muted">
          Connection facts live on the <Link href={`/resources/${id}`} className="text-accent hover:underline">resource view</Link>.
        </p>
        {/* ── Pause: what the DESIGNER is shown. Above Remove, and worded so
            the difference between the two is readable in one pass — that is
            the whole reason both exist on this page. ─────────────────────── */}
        <div className="flex flex-col gap-3 rounded-lg border border-line bg-surface px-4 py-3 text-sm sm:flex-row sm:items-center sm:justify-between">
          <span className="text-muted">
            {conn.paused_from_model ? (
              <>
                <strong className="text-warn">Paused.</strong> This data source is left out of the
                workspace manifest and out of the list of components the designer and the chat
                builder are given, so nothing new will be built against it. Automations that already
                read it are unaffected — they still validate, they still run, and none has been
                turned off.
              </>
            ) : (
              <>
                Pausing hides this data source from the designer: it is left out of the workspace
                manifest and out of the components the designer and the chat builder are offered, so
                nothing new gets built against it. Nothing is deleted and nothing stops — every
                automation already reading it keeps validating and keeps running.
              </>
            )}
          </span>
          <Button
            variant="subtle"
            className="shrink-0"
            onClick={togglePause}
            disabled={busy === "pause"}
          >
            {busy === "pause" ? "Saving…" : conn.paused_from_model ? "Resume" : "Pause"}
          </Button>
        </div>

        <div className="flex flex-col gap-3 rounded-lg border border-line bg-surface px-4 py-3 text-sm sm:flex-row sm:items-center sm:justify-between">
          <span className="text-muted">
            Removing this data source forgets its credential and everything Tether discovered about
            it. Any operation written against it, and any flow step that calls one, stops working
            until it is registered again. The database itself is not touched.
          </span>
          <Button variant="danger" className="shrink-0" onClick={() => setConfirmDel(true)}>
            <Trash s={15} /> Remove data source
          </Button>
        </div>
      </Zone>

      {/* Columns for one table */}
      <Modal
        open={!!inspect}
        onClose={() => setInspect(null)}
        title={inspect ? inspect.title : ""}
      >
        {inspect && (() => {
          // Read from the CURRENT tree, so a saved declaration shows at once.
          const node = findNode(metadata ?? [], inspect.node.name) ?? inspect.node;
          const columns = columnsOf(node);
          return (
          <div className="space-y-3">
            {columns.length === 0 ? (
              <p className="text-sm text-muted">No columns were recorded for this table.</p>
            ) : (
              <DataTable
                set="column"
                caption={`Columns of ${inspect.title}`}
                heads={{ identity: "Column", kind: "Type", nullable: "Null?", keyRole: "Key", holds: "Holds" }}
                rows={columnRows(columns, inspect.keyPrefix)}
                empty="No columns were recorded for this table."
              />
            )}
            <p className="text-xs text-muted">
              Tether does not read rows from your data source to show you here. A flow reads rows by
              running a query, and you can see exactly what it read on the run&apos;s page.
            </p>
            <p className="text-xs text-muted">
              Declaring a column an email address is a statement Tether keeps — it lets an automation send to the people in the
              rows. Your database is not changed.
            </p>
          </div>
          );
        })()}
      </Modal>

      <Confirm
        open={confirmDel}
        title="Remove data source?"
        body={`Tether will forget ${conn.name}'s credentials and discovered schema. Any flow whose steps read from it will fail until it is re-registered.`}
        confirmLabel="Remove"
        danger
        onConfirm={remove}
        onClose={() => setConfirmDel(false)}
      />
    </Page>
  );
}
